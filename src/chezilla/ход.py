from dataclasses import dataclass
from datetime import date


@dataclass(frozen=True)
class Диалог:
    pass


@dataclass(frozen=True)
class Сообщение:
    текст: str
    товарная_группа: str
    операция: str
    дата_события: date


@dataclass(frozen=True)
class Норма:
    товарная_группа: str
    операция: str
    действует_с: date
    действует_по: date
    источник: str
    следующий_шаг: str


@dataclass(frozen=True)
class ХЗЧЗ:
    нормы: tuple[Норма, ...]


@dataclass(frozen=True)
class Ответ:
    товарная_группа: str
    дата_нормы: date
    источник: str
    следующий_шаг: str


@dataclass(frozen=True)
class РезультатХода:
    ответ: Ответ
    диалог: Диалог


def ход_диалога(
    *,
    дата_вопроса: date,
    диалог: Диалог,
    сообщение: Сообщение,
    хзчз: ХЗЧЗ,
) -> РезультатХода:
    норма = next(
        кандидат
        for кандидат in хзчз.нормы
        if кандидат.товарная_группа == сообщение.товарная_группа
        and кандидат.операция == сообщение.операция
        and кандидат.действует_с <= сообщение.дата_события <= кандидат.действует_по
    )
    return РезультатХода(
        ответ=Ответ(
            товарная_группа=сообщение.товарная_группа,
            дата_нормы=сообщение.дата_события,
            источник=норма.источник,
            следующий_шаг=норма.следующий_шаг,
        ),
        диалог=диалог,
    )
