from dataclasses import dataclass
from datetime import date


@dataclass(frozen=True)
class Диалог:
    pass


@dataclass(frozen=True)
class Событие:
    операция: str
    дата: date | None = None


@dataclass(frozen=True)
class Сообщение:
    текст: str
    товарная_группа: str
    события: tuple[Событие, ...]


@dataclass(frozen=True)
class Норма:
    товарная_группа: str
    операция: str
    действует_с: date
    действует_по: date
    источник: str
    следующий_шаг: str


@dataclass(frozen=True)
class ХЗЧЗ:
    нормы: tuple[Норма, ...]


@dataclass(frozen=True)
class Пара:
    операция: str | None
    дата_нормы: date
    источник: str | None
    следующий_шаг: str | None
    фраза_дня_вопроса: str | None = None
    фраза_пустых_знаний: str | None = None


@dataclass(frozen=True)
class Ответ:
    товарная_группа: str
    пары: tuple[Пара, ...]


@dataclass(frozen=True)
class РезультатХода:
    ответ: Ответ
    диалог: Диалог


_ФРАЗА_ДНЯ_ВОПРОСА = "Дата нормы — день вопроса."
_ФРАЗА_ПУСТЫХ_ЗНАНИЙ = "В знаниях нет требования на эту дату."


def ход_диалога(
    *,
    дата_вопроса: date,
    диалог: Диалог,
    сообщение: Сообщение,
    хзчз: ХЗЧЗ,
) -> РезультатХода:
    пары: list[Пара] = []
    события: tuple[Событие | None, ...] = (
        сообщение.события if сообщение.события else (None,)
    )
    for событие in события:
        if событие is None:
            пары.append(
                Пара(
                    операция=None,
                    дата_нормы=дата_вопроса,
                    источник=None,
                    следующий_шаг=None,
                    фраза_дня_вопроса=_ФРАЗА_ДНЯ_ВОПРОСА,
                )
            )
            continue
        дата_нормы = событие.дата if событие.дата is not None else дата_вопроса
        норма = next(
            (
                кандидат
                for кандидат in хзчз.нормы
                if кандидат.товарная_группа == сообщение.товарная_группа
                and кандидат.операция == событие.операция
                and кандидат.действует_с <= дата_нормы <= кандидат.действует_по
            ),
            None,
        )
        источник: str | None
        следующий_шаг: str | None
        фраза_пустых_знаний: str | None
        if норма is None:
            источник = None
            следующий_шаг = None
            фраза_пустых_знаний = _ФРАЗА_ПУСТЫХ_ЗНАНИЙ
        else:
            источник = норма.источник
            следующий_шаг = норма.следующий_шаг
            фраза_пустых_знаний = None
        пары.append(
            Пара(
                операция=событие.операция,
                дата_нормы=дата_нормы,
                источник=источник,
                следующий_шаг=следующий_шаг,
                фраза_дня_вопроса=(
                    None
                    if событие.дата is not None
                    else _ФРАЗА_ДНЯ_ВОПРОСА
                ),
                фраза_пустых_знаний=фраза_пустых_знаний,
            )
        )
    return РезультатХода(
        ответ=Ответ(
            товарная_группа=сообщение.товарная_группа,
            пары=tuple(пары),
        ),
        диалог=диалог,
    )
