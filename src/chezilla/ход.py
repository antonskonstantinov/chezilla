from dataclasses import dataclass
from datetime import date
from typing import TypeVar


@dataclass(frozen=True)
class Диалог:
    товарная_группа: str | None = None
    явный_выбор: bool = False


@dataclass(frozen=True)
class Событие:
    операция: str
    дата: date | None = None


@dataclass(frozen=True)
class Сообщение:
    текст: str
    названные_группы: tuple[str, ...]
    события: tuple[Событие, ...]
    явный_выбор: str | None = None
    группа_следующего_шага: str | None = None
    сквозной: bool = False


@dataclass(frozen=True)
class Норма:
    товарная_группа: str
    операция: str
    действует_с: date
    действует_по: date
    источник: str | None
    следующий_шаг: str


@dataclass(frozen=True)
class Практика:
    операция: str
    действует_с: date
    действует_по: date
    источник: str | None
    способ: str


@dataclass(frozen=True)
class БлокГруппы:
    товарная_группа: str
    нормы: tuple[Норма, ...] = ()
    практики: tuple[Практика, ...] = ()


@dataclass(frozen=True)
class РегламентПровайдера:
    операция: str
    действует_с: date
    действует_по: date
    источник: str | None
    следующий_шаг: str


@dataclass(frozen=True)
class БлокПровайдера:
    провайдер: str
    регламенты: tuple[РегламентПровайдера, ...] = ()
    практики: tuple[Практика, ...] = ()


@dataclass(frozen=True)
class ХЗЧЗ:
    нормы: tuple[Норма, ...] = ()
    блоки_групп: tuple[БлокГруппы, ...] = ()
    блоки_провайдеров: tuple[БлокПровайдера, ...] = ()


@dataclass(frozen=True)
class Пара:
    операция: str | None
    дата_нормы: date
    источник: str | None
    следующий_шаг: str | None
    фраза_дня_вопроса: str | None = None
    фраза_пустых_знаний: str | None = None
    источник_практики: str | None = None
    способ: str | None = None


@dataclass(frozen=True)
class Ответ:
    товарная_группа: str | None
    пары: tuple[Пара, ...]
    фраза_о_выборе: str | None = None
    вопрос_о_группе: str | None = None


@dataclass(frozen=True)
class РезультатХода:
    ответ: Ответ
    диалог: Диалог


_ФРАЗА_ДНЯ_ВОПРОСА = "Дата нормы — день вопроса."
_ФРАЗА_ПУСТЫХ_ЗНАНИЙ = "В знаниях этого нет."
_ФРАЗА_О_ВЫБОРЕ = (
    "Советник выбрал товарную группу «{группа}». "
    "Сменить её можно явным выбором."
)

_Слой = TypeVar("_Слой", Норма, Практика)


def _нормы_группы(хзчз: ХЗЧЗ, товарная_группа: str) -> tuple[Норма, ...]:
    return tuple(
        норма
        for норма in хзчз.нормы
        if норма.товарная_группа == товарная_группа
    ) + tuple(
        норма
        for блок in хзчз.блоки_групп
        if блок.товарная_группа == товарная_группа
        for норма in блок.нормы
        if норма.товарная_группа == товарная_группа
    )


def _практики_группы(хзчз: ХЗЧЗ, товарная_группа: str) -> tuple[Практика, ...]:
    return tuple(
        практика
        for блок in хзчз.блоки_групп
        if блок.товарная_группа == товарная_группа
        for практика in блок.практики
    )


def _слой_с_источником(
    слои: tuple[_Слой, ...],
    *,
    операция: str,
    дата_нормы: date,
) -> _Слой | None:
    for слой in слои:
        if (
            слой.операция == операция
            and слой.действует_с <= дата_нормы <= слой.действует_по
            and слой.источник
        ):
            return слой
    return None


def _фраза_о_выборе(группа: str) -> str:
    return _ФРАЗА_О_ВЫБОРЕ.format(группа=группа)


def _вопрос_о_группе(группы: tuple[str, ...]) -> str:
    перечень = " или ".join(f"«{группа}»" for группа in группы)
    return f"Какую товарную группу разобрать: {перечень}?"


@dataclass(frozen=True)
class _Назначение:
    диалог: Диалог
    группа: str | None
    фраза_о_выборе: str | None = None
    вопрос_о_группе: str | None = None


def _без_группы(
    диалог: Диалог,
    *,
    вопрос_о_группе: str | None = None,
) -> _Назначение:
    return _Назначение(
        диалог=диалог,
        группа=None,
        вопрос_о_группе=вопрос_о_группе,
    )


def _группа_вопроса(сообщение: Сообщение, диалог: Диалог) -> str | None:
    if сообщение.группа_следующего_шага is not None:
        return сообщение.группа_следующего_шага
    if сообщение.названные_группы:
        return сообщение.названные_группы[0]
    return диалог.товарная_группа


def _назначить_группу(диалог: Диалог, сообщение: Сообщение) -> _Назначение:
    if сообщение.сквозной:
        return _без_группы(диалог)
    if сообщение.явный_выбор is not None:
        return _Назначение(
            диалог=Диалог(
                товарная_группа=сообщение.явный_выбор,
                явный_выбор=True,
            ),
            группа=сообщение.явный_выбор,
        )
    if (
        сообщение.группа_следующего_шага is None
        and len(сообщение.названные_группы) >= 2
        and not диалог.явный_выбор
    ):
        return _без_группы(
            Диалог(),
            вопрос_о_группе=_вопрос_о_группе(сообщение.названные_группы),
        )
    группа = _группа_вопроса(сообщение, диалог)
    if группа is None:
        return _без_группы(диалог)
    if (
        диалог.явный_выбор
        and диалог.товарная_группа is not None
        and диалог.товарная_группа != группа
    ):
        return _Назначение(
            диалог=диалог,
            группа=диалог.товарная_группа,
            фраза_о_выборе=_фраза_о_выборе(диалог.товарная_группа),
        )
    if диалог.товарная_группа != группа:
        return _Назначение(
            диалог=Диалог(товарная_группа=группа),
            группа=группа,
            фраза_о_выборе=_фраза_о_выборе(группа),
        )
    return _Назначение(диалог=диалог, группа=группа)


def ход_диалога(
    *,
    дата_вопроса: date,
    диалог: Диалог,
    сообщение: Сообщение,
    хзчз: ХЗЧЗ,
) -> РезультатХода:
    назначение = _назначить_группу(диалог, сообщение)
    if назначение.группа is None:
        return РезультатХода(
            ответ=Ответ(
                товарная_группа=None,
                пары=(),
                фраза_о_выборе=назначение.фраза_о_выборе,
                вопрос_о_группе=назначение.вопрос_о_группе,
            ),
            диалог=назначение.диалог,
        )
    группа = назначение.группа
    фраза_о_выборе = назначение.фраза_о_выборе
    диалог = назначение.диалог
    пары: list[Пара] = []
    события: tuple[Событие | None, ...] = (
        сообщение.события if сообщение.события else (None,)
    )
    for событие in события:
        if событие is None:
            пары.append(
                Пара(
                    операция=None,
                    дата_нормы=дата_вопроса,
                    источник=None,
                    следующий_шаг=None,
                    фраза_дня_вопроса=_ФРАЗА_ДНЯ_ВОПРОСА,
                )
            )
            continue
        дата_нормы = событие.дата if событие.дата is not None else дата_вопроса
        норма = _слой_с_источником(
            _нормы_группы(хзчз, группа),
            операция=событие.операция,
            дата_нормы=дата_нормы,
        )
        практика = _слой_с_источником(
            _практики_группы(хзчз, группа),
            операция=событие.операция,
            дата_нормы=дата_нормы,
        )
        if норма is not None:
            источник = норма.источник
            следующий_шаг = норма.следующий_шаг
            источник_практики = None
            способ = None
            фраза_пустых_знаний = None
        elif практика is not None:
            источник = None
            следующий_шаг = None
            источник_практики = практика.источник
            способ = практика.способ
            фраза_пустых_знаний = None
        else:
            источник = None
            следующий_шаг = None
            источник_практики = None
            способ = None
            фраза_пустых_знаний = _ФРАЗА_ПУСТЫХ_ЗНАНИЙ
        пары.append(
            Пара(
                операция=событие.операция,
                дата_нормы=дата_нормы,
                источник=источник,
                следующий_шаг=следующий_шаг,
                фраза_дня_вопроса=(
                    None
                    if событие.дата is not None
                    else _ФРАЗА_ДНЯ_ВОПРОСА
                ),
                фраза_пустых_знаний=фраза_пустых_знаний,
                источник_практики=источник_практики,
                способ=способ,
            )
        )
    return РезультатХода(
        ответ=Ответ(
            товарная_группа=группа,
            пары=tuple(пары),
            фраза_о_выборе=фраза_о_выборе,
        ),
        диалог=диалог,
    )
