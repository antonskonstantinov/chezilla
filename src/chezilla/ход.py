_ВИДЫ_УПАКОВКИ = frozenset({"АТК", "ОСУ"})


def _имя_операции(имя: str, особые: frozenset[str]) -> str | None:
    if имя in _УНИВЕРСАЛЬНЫЕ_ОПЕРАЦИИ:
        return имя
    родитель = _ВИДЫ_ОПЕРАЦИЙ.get(имя)
    if родитель is not None:
        return родитель
    if имя in особые:
        return имя
    return None


def _операция_события(событие: Событие, особые: frozenset[str]) -> str | None:
    if событие.операция in _ВИДЫ_УПАКОВКИ:
        return None
    return _имя_операции(событие.операция, особые)


def _особые_операции(хзчз: ХЗЧЗ, товарная_группа: str) -> frozenset[str]:
    return frozenset(
        операция
        for блок in хзчз.блоки_групп
        if блок.товарная_группа == товарная_группа
        for операция in блок.особые_операции
    )


_ФРАЗА_О_ВЫБОРЕ = (
    "Советник выбрал товарную группу «{группа}». "
    "Сменить её можно явным выбором."
)
_ФРАЗА_ПРОВАЙДЕРА = "Провайдер диалога — «{провайдер}»."

_Слой = TypeVar("_Слой", Норма, Практика, РегламентПровайдера)


def _нормы_группы(хзчз: ХЗЧЗ, товарная_группа: str) -> tuple[Норма, ...]:
    return tuple(
        норма
        for норма in хзчз.нормы
        if норма.товарная_группа == товарная_группа
    ) + tuple(
        норма
        for блок in хзчз.блоки_групп
        if блок.товарная_группа == товарная_группа
        for норма in блок.нормы
        if норма.товарная_группа == товарная_группа
    )


def _практики_группы(хзчз: ХЗЧЗ, товарная_группа: str) -> tuple[Практика, ...]:
    return tuple(
        практика
        for блок in хзчз.блоки_групп
        if блок.товарная_группа == товарная_группа
        for практика in блок.практики
    )


def _слой_с_источником(
    слои: tuple[_Слой, ...],
    *,
    операция: str,
    дата_нормы: date,
) -> _Слой | None:
    for слой in слои:
        if (
            слой.операция == операция
            and слой.действует_с <= дата_нормы <= слой.действует_по
            and слой.источник
        ):
            return слой
    return None


def _охват_включает(охват: Охват, товарная_группа: str) -> bool:
    if товарная_группа in охват.исключения:
        return False
    if охват.все:
        return True
    return товарная_группа in охват.товарные_группы


def _ширина_охвата(охват: Охват) -> tuple[int, int]:
    if охват.все:
        return (1, 0)
    return (0, len(frozenset(охват.товарные_группы)))


def _самые_узкие(нормы: tuple[ОбщаяНорма, ...]) -> tuple[ОбщаяНорма, ...]:
    ширина = min(_ширина_охвата(норма.охват) for норма in нормы)
    return tuple(
        норма for норма in нормы if _ширина_охвата(норма.охват) == ширина
    )


_ПОРЯДОК_СИЛЫ_АКТА: tuple[СилаАкта, ...] = (
    СилаАкта.федеральный_закон,
    СилаАкта.акт_правительства,
    СилаАкта.ведомственный_акт,
    СилаАкта.официальная_публикация_оператора,
)


def _ключ_охвата(
    охват: Охват,
) -> tuple[bool, frozenset[str], frozenset[str]]:
    return (охват.все, frozenset(охват.товарные_группы), frozenset(охват.исключения))


def _один_охват(нормы: tuple[ОбщаяНорма, ...]) -> bool:
    return len({_ключ_охвата(норма.охват) for норма in нормы}) == 1


def _сильнейшие(нормы: tuple[ОбщаяНорма, ...]) -> tuple[ОбщаяНорма, ...]:
    ранг = min(_ПОРЯДОК_СИЛЫ_АКТА.index(норма.сила_акта) for норма in нормы)
    return tuple(
        норма
        for норма in нормы
        if _ПОРЯДОК_СИЛЫ_АКТА.index(норма.сила_акта) == ранг
    )


def _поздние(нормы: tuple[ОбщаяНорма, ...]) -> tuple[ОбщаяНорма, ...]:
    дата = max(норма.вступила_в_силу for норма in нормы)
    return tuple(норма for норма in нормы if норма.вступила_в_силу == дата)


def _по_охватам(
    нормы: tuple[ОбщаяНорма, ...],
) -> tuple[tuple[ОбщаяНорма, ...], ...]:
    по_ключу: dict[
        tuple[bool, frozenset[str], frozenset[str]],
        list[ОбщаяНорма],
    ] = {}
    for норма in нормы:
        по_ключу.setdefault(_ключ_охвата(норма.охват), []).append(норма)
    return tuple(tuple(нормы_охвата) for нормы_охвата in по_ключу.values())


def _кандидаты_общей(нормы: tuple[ОбщаяНорма, ...]) -> tuple[ОбщаяНорма, ...]:
    if not нормы:
        return ()
    внутри: list[ОбщаяНорма] = []
    for нормы_охвата in _по_охватам(нормы):
        внутри.extend(_поздние(_сильнейшие(нормы_охвата)))
    return _самые_узкие(tuple(внутри))


def _источники_норм(нормы: tuple[ОбщаяНорма, ...]) -> tuple[str, ...]:
    источники: list[str] = []
    for норма in нормы:
        if норма.источник is not None:
            источники.append(норма.источник)
    return tuple(источники)


@dataclass(frozen=True)
class _СлойПары:
    источник: str | None = None
    следующий_шаг: str | None = None
    источник_практики: str | None = None
    способ: str | None = None
    фраза_пустых_знаний: str | None = None
    фраза_расхождения: str | None = None
    фраза_отдельных_сведений: str | None = None
    фраза_оговорки: str | None = None
    фраза_нет_нормы: str | None = None
    источник_регламента: str | None = None
    регламент: str | None = None
    фраза_оговорки_регламента: str | None = None
    охват: Охват | None = None
    источники: tuple[str, ...] = ()


def _практика_рядом_с_нормой(
    практика: Практика | None,
    следующий_шаг: str,
) -> tuple[str | None, str | None, str | None]:
    if практика is None:
        return None, None, None
    if практика.способ == следующий_шаг:
        return практика.источник, практика.способ, None
    return практика.источник, практика.способ, _ФРАЗА_ОГОВОРКИ


def _регламент_рядом_с_нормой(
    регламент: РегламентПровайдера | None,
    следующий_шаг: str,
) -> tuple[str | None, str | None, str | None]:
    if регламент is None:
        return None, None, None
    if регламент.следующий_шаг == следующий_шаг:
        return регламент.источник, регламент.следующий_шаг, None
    return регламент.источник, регламент.следующий_шаг, _ФРАЗА_ОГОВОРКИ_РЕГЛАМЕНТА


def _слой_выбранной_нормы(
    *,
    источник: str | None,
    следующий_шаг: str,
    практика: Практика | None,
    регламент: РегламентПровайдера | None,
    фраза_расхождения: str | None = None,
    фраза_отдельных_сведений: str | None = None,
    охват: Охват | None = None,
) -> _СлойПары:
    источник_практики, способ, фраза_оговорки = _практика_рядом_с_нормой(
        практика, следующий_шаг
    )
    источник_регламента, текст_регламента, фраза_оговорки_регламента = (
        _регламент_рядом_с_нормой(регламент, следующий_шаг)
    )
    return _СлойПары(
        источник=источник,
        следующий_шаг=следующий_шаг,
        источник_практики=источник_практики,
        способ=способ,
        фраза_расхождения=фраза_расхождения,
        фраза_отдельных_сведений=фраза_отдельных_сведений,
        фраза_оговорки=фраза_оговорки,
        источник_регламента=источник_регламента,
        регламент=текст_регламента,
        фраза_оговорки_регламента=фраза_оговорки_регламента,
        охват=охват,
    )


def _слой_пары(
    *,
    норма: Норма | None,
    общие: tuple[ОбщаяНорма, ...],
    практика: Практика | None,
    регламент: РегламентПровайдера | None = None,
) -> _СлойПары:
    кандидаты = _кандидаты_общей(общие)
    if норма is not None:
        фраза_расхождения = None
        if (
            len(кандидаты) == 1
            and кандидаты[0].следующий_шаг != норма.следующий_шаг
        ):
            фраза_расхождения = _ФРАЗА_РАСХОЖДЕНИЯ
        return _слой_выбранной_нормы(
            источник=норма.источник,
            следующий_шаг=норма.следующий_шаг,
            практика=практика,
            регламент=регламент,
            фраза_расхождения=фраза_расхождения,
        )
    if len(кандидаты) == 1:
        общая = кандидаты[0]
        return _слой_выбранной_нормы(
            источник=общая.источник,
            следующий_шаг=общая.следующий_шаг,
            практика=практика,
            регламент=регламент,
            фраза_отдельных_сведений=_ФРАЗА_ОТДЕЛЬНЫХ_СВЕДЕНИЙ,
            охват=общая.охват,
        )
    if кандидаты:
        return _СлойПары(
            фраза_отдельных_сведений=_ФРАЗА_ОТДЕЛЬНЫХ_СВЕДЕНИЙ,
            охват=кандидаты[0].охват if _один_охват(кандидаты) else None,
            источники=_источники_норм(кандидаты),
        )
    if практика is not None:
        return _СлойПары(
            следующий_шаг=практика.способ,
            источник_практики=практика.источник,
            способ=практика.способ,
            фраза_нет_нормы=_ФРАЗА_НЕТ_НОРМЫ,
            источник_регламента=None if регламент is None else регламент.источник,
            регламент=None if регламент is None else регламент.следующий_шаг,
        )
    if регламент is not None:
        return _СлойПары(
            следующий_шаг=регламент.следующий_шаг,
            источник_регламента=регламент.источник,
            регламент=регламент.следующий_шаг,
            фраза_нет_нормы=_ФРАЗА_НЕТ_НОРМЫ,
        )
    return _СлойПары(фраза_пустых_знаний=_ФРАЗА_ПУСТЫХ_ЗНАНИЙ)


def _общие_на_дату(
    хзчз: ХЗЧЗ,
    *,
    товарная_группа: str,
    операция: str,
    дата_нормы: date,
) -> tuple[ОбщаяНорма, ...]:
    return tuple(
        норма
        for норма in хзчз.блок_общих_норм.нормы
        if норма.операция == операция
        and норма.действует_с <= дата_нормы <= норма.действует_по
        and bool(норма.источник)
        and _охват_включает(норма.охват, товарная_группа)
    )


def _фраза_о_выборе(группа: str) -> str:
    return _ФРАЗА_О_ВЫБОРЕ.format(группа=группа)


def _вопрос_о_группе(группы: tuple[str, ...]) -> str:
    перечень = " или ".join(f"«{группа}»" for группа in группы)
    return f"Какую товарную группу разобрать: {перечень}?"


@dataclass(frozen=True)
class _Назначение:
    диалог: Диалог
    группа: str | None
    фраза_о_выборе: str | None = None
    вопрос_о_группе: str | None = None


def _без_группы(
    диалог: Диалог,
    *,
    вопрос_о_группе: str | None = None,
) -> _Назначение:
    return _Назначение(
        диалог=диалог,
        группа=None,
        вопрос_о_группе=вопрос_о_группе,
    )


def _товарная_группа_сообщения(сообщение: Сообщение) -> str | None:
    if сообщение.группа_следующего_шага is not None:
        return сообщение.группа_следующего_шага
    if сообщение.товарные_группы:
        return сообщение.товарные_группы[0]
    return None


def _вопрос_называет_другую_группу(диалог: Диалог, сообщение: Сообщение) -> bool:
    if диалог.товарная_группа is None:
        return False
    return any(
        группа != диалог.товарная_группа for группа in сообщение.товарные_группы
    )


def _назначить_группу(диалог: Диалог, сообщение: Сообщение) -> _Назначение:
    if сообщение.явная_товарная_группа is not None:
        return _Назначение(
            диалог=Диалог(
                товарная_группа=сообщение.явная_товарная_группа,
                явный_выбор=True,
                провайдер=диалог.провайдер,
            ),
            группа=сообщение.явная_товарная_группа,
        )
    if сообщение.сквозной:
        return _без_группы(диалог)
    if (
        сообщение.группа_следующего_шага is None
        and len(сообщение.товарные_группы) >= 2
        and not диалог.явный_выбор
    ):
        return _без_группы(
            Диалог(провайдер=диалог.провайдер),
            вопрос_о_группе=_вопрос_о_группе(сообщение.товарные_группы),
        )
    группа = _товарная_группа_сообщения(сообщение) or диалог.товарная_группа
    if группа is None:
        return _без_группы(диалог)
    if (
        диалог.явный_выбор
        and диалог.товарная_группа is not None
        and (
            диалог.товарная_группа != группа
            or _вопрос_называет_другую_группу(диалог, сообщение)
        )
    ):
        return _Назначение(
            диалог=диалог,
            группа=диалог.товарная_группа,
            фраза_о_выборе=_фраза_о_выборе(диалог.товарная_группа),
        )
    if диалог.товарная_группа != группа:
        return _Назначение(
            диалог=Диалог(товарная_группа=группа, провайдер=диалог.провайдер),
            группа=группа,
            фраза_о_выборе=_фраза_о_выборе(группа),
        )
    return _Назначение(диалог=диалог, группа=группа)


def _блок_провайдера(хзчз: ХЗЧЗ, провайдер: str) -> БлокПровайдера | None:
    for блок in хзчз.блоки_провайдеров:
        if блок.провайдер == провайдер:
            return блок
    return None


def _провайдер_хода(диалог: Диалог, сообщение: Сообщение) -> str | None:
    if сообщение.провайдер_ситуации is not None:
        return сообщение.провайдер_ситуации
    if len(сообщение.провайдеры) == 1:
        return сообщение.провайдеры[0]
    return диалог.провайдер


def _фраза_провайдера(было: str | None, стало: str | None) -> str | None:
    if стало is None or стало == было:
        return None
    return _ФРАЗА_ПРОВАЙДЕРА.format(провайдер=стало)


def _соединить_фразу(*части: str | None) -> str | None:
    текст = " ".join(часть for часть in части if часть)
    return текст or None


def _с_провайдером(диалог: Диалог, провайдер: str | None) -> Диалог:
    if диалог.провайдер == провайдер:
        return диалог
    return Диалог(
        товарная_группа=диалог.товарная_группа,
        явный_выбор=диалог.явный_выбор,
        провайдер=провайдер,
    )


def ход_диалога(
    *,
    дата_вопроса: date,
    диалог: Диалог,
    сообщение: Сообщение,
    хзчз: ХЗЧЗ,
) -> РезультатХода:
    назначение = _назначить_группу(диалог, сообщение)
    провайдер = _провайдер_хода(назначение.диалог, сообщение)
    фраза_о_выборе = _соединить_фразу(
        назначение.фраза_о_выборе,
        _фраза_провайдера(диалог.провайдер, провайдер),
    )
    диалог = _с_провайдером(назначение.диалог, провайдер)
    if назначение.группа is None:
        return РезультатХода(
            ответ=Ответ(
                товарная_группа=None,
                пары=(),
                фраза_о_выборе=фраза_о_выборе,
                вопрос_о_группе=назначение.вопрос_о_группе,
            ),
            диалог=диалог,
        )
    группа = назначение.группа
    if not сообщение.события:
        return РезультатХода(
            ответ=Ответ(
                товарная_группа=группа,
                пары=(),
                фраза_о_выборе=фраза_о_выборе,
                вопрос_об_операции=_ФРАЗА_ВОПРОСА_ОБ_ОПЕРАЦИИ,
            ),
            диалог=диалог,
        )
    пары: list[Пара] = []
    имя_вне_списка = False
    особые = _особые_операции(хзчз, группа)
    for событие in сообщение.события:
        операция = _операция_события(событие, особые)
        if операция is None:
            имя_вне_списка = True
            continue
        дата_нормы = событие.дата if событие.дата is not None else дата_вопроса
        норма = _слой_с_источником(
            _нормы_группы(хзчз, группа),
            операция=операция,
            дата_нормы=дата_нормы,
        )
        общие = _общие_на_дату(
            хзчз,
            товарная_группа=группа,
            операция=операция,
            дата_нормы=дата_нормы,
        )
        практика = _слой_с_источником(
            _практики_группы(хзчз, группа),
            операция=операция,
            дата_нормы=дата_нормы,
        )
        регламент = None
        фраза_нет_регламента = None
        if сообщение.провайдер_ситуации is not None:
            блок_провайдера = _блок_провайдера(хзчз, сообщение.провайдер_ситуации)
            if блок_провайдера is None:
                фраза_нет_регламента = _ФРАЗА_НЕТ_РЕГЛАМЕНТА
            else:
                регламент = _слой_с_источником(
                    блок_провайдера.регламенты,
                    операция=операция,
                    дата_нормы=дата_нормы,
                )
                практика_провайдера = _слой_с_источником(
                    блок_провайдера.практики,
                    операция=операция,
                    дата_нормы=дата_нормы,
                )
                if практика_провайдера is not None:
                    практика = практика_провайдера
        слой = _слой_пары(
            норма=норма,
            общие=общие,
            практика=практика,
            регламент=регламент,
        )
        пары.append(
            Пара(
                операция=операция,
                дата_нормы=дата_нормы,
                источник=слой.источник,
                следующий_шаг=слой.следующий_шаг,
                фраза_дня_вопроса=(
                    None
                    if событие.дата is not None
                    else _ФРАЗА_ДНЯ_ВОПРОСА
                ),
                фраза_пустых_знаний=слой.фраза_пустых_знаний,
                источник_практики=слой.источник_практики,
                способ=слой.способ,
                отмена=событие.отмена,
                фраза_расхождения=слой.фраза_расхождения,
                фраза_отдельных_сведений=слой.фраза_отдельных_сведений,
                фраза_оговорки=слой.фраза_оговорки,
                фраза_нет_нормы=слой.фраза_нет_нормы,
                источник_регламента=слой.источник_регламента,
                регламент=слой.регламент,
                фраза_оговорки_регламента=слой.фраза_оговорки_регламента,
                фраза_нет_регламента=фраза_нет_регламента,
                охват=слой.охват,
                источники=слой.источники,
            )
        )
    return РезультатХода(
        ответ=Ответ(
            товарная_группа=группа,
            пары=tuple(пары),
            фраза_о_выборе=фраза_о_выборе,
            вопрос_об_операции=(
                _ФРАЗА_ВОПРОСА_ОБ_ОПЕРАЦИИ if имя_вне_списка else None
            ),
        ),
        диалог=диалог,
    )
