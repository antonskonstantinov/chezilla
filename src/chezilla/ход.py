from dataclasses import dataclass
from datetime import date
from enum import Enum
from typing import TypeVar


@dataclass(frozen=True)
class Диалог:
    товарная_группа: str | None = None
    явный_выбор: bool = False
    провайдер: str | None = None


@dataclass(frozen=True)
class Событие:
    операция: str
    дата: date | None = None
    отмена: bool = False


@dataclass(frozen=True)
class Сообщение:
    текст: str
    товарные_группы: tuple[str, ...]
    события: tuple[Событие, ...]
    явная_товарная_группа: str | None = None
    группа_следующего_шага: str | None = None
    сквозной: bool = False
    провайдеры: tuple[str, ...] = ()
    провайдер_ситуации: str | None = None


class СилаАкта(Enum):
    федеральный_закон = "федеральный закон"
    акт_правительства = "акт Правительства"
    ведомственный_акт = "ведомственный акт"
    официальная_публикация_оператора = "официальная публикация оператора"


@dataclass(frozen=True)
class Охват:
    товарные_группы: tuple[str, ...] = ()
    все: bool = False
    исключения: tuple[str, ...] = ()


@dataclass(frozen=True)
class Норма:
    товарная_группа: str
    операция: str
    действует_с: date
    действует_по: date
    источник: str | None
    следующий_шаг: str


@dataclass(frozen=True)
class ОбщаяНорма:
    операция: str
    действует_с: date
    действует_по: date
    охват: Охват
    сила_акта: СилаАкта
    вступила_в_силу: date
    источник: str | None
    следующий_шаг: str


@dataclass(frozen=True)
class Практика:
    операция: str
    действует_с: date
    действует_по: date
    источник: str | None
    способ: str
    сведения_об_участнике: str | None = None


@dataclass(frozen=True)
class БлокГруппы:
    товарная_группа: str
    нормы: tuple[Норма, ...] = ()
    практики: tuple[Практика, ...] = ()
    особые_операции: tuple[str, ...] = ()


@dataclass(frozen=True)
class РегламентПровайдера:
    операция: str
    действует_с: date
    действует_по: date
    источник: str | None
    следующий_шаг: str


@dataclass(frozen=True)
class БлокПровайдера:
    провайдер: str
    регламенты: tuple[РегламентПровайдера, ...] = ()
    практики: tuple[Практика, ...] = ()


@dataclass(frozen=True)
class БлокОбщихНорм:
    нормы: tuple[ОбщаяНорма, ...] = ()


@dataclass(frozen=True)
class ХЗЧЗ:
    нормы: tuple[Норма, ...] = ()
    блоки_групп: tuple[БлокГруппы, ...] = ()
    блоки_провайдеров: tuple[БлокПровайдера, ...] = ()
    блок_общих_норм: БлокОбщихНорм = БлокОбщихНорм()


@dataclass(frozen=True)
class Пара:
    операция: str | None
    дата_нормы: date
    источник: str | None
    следующий_шаг: str | None
    фраза_дня_вопроса: str | None = None
    фраза_пустых_знаний: str | None = None
    источник_практики: str | None = None
    способ: str | None = None
    отмена: bool = False
    фраза_расхождения: str | None = None
    фраза_отдельных_сведений: str | None = None
    фраза_оговорки: str | None = None
    фраза_нет_нормы: str | None = None
    источник_регламента: str | None = None
    регламент: str | None = None
    фраза_оговорки_регламента: str | None = None
    фраза_нет_регламента: str | None = None
    охват: Охват | None = None
    источники: tuple[str, ...] = ()


@dataclass(frozen=True)
class Ответ:
    товарная_группа: str | None
    пары: tuple[Пара, ...]
    фраза_о_выборе: str | None = None
    вопрос_о_группе: str | None = None
    вопрос_об_операции: str | None = None


@dataclass(frozen=True)
class РезультатХода:
    ответ: Ответ
    диалог: Диалог


