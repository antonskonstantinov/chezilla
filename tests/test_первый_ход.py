from datetime import date

from chezilla.ход import Диалог, Норма, Событие, Сообщение, ХЗЧЗ, ход_диалога


ИСТОЧНИК = "Постановление Правительства РФ от 26.04.2019 № 515"
СЛЕДУЮЩИЙ_ШАГ = "Подать сведения о приёмке"


def _хранилище() -> ХЗЧЗ:
    return ХЗЧЗ(
        нормы=(
            Норма(
                товарная_группа="моторные масла",
                операция="приёмка",
                действует_с=date(2026, 1, 1),
                действует_по=date(2026, 12, 31),
                источник=ИСТОЧНИК,
                следующий_шаг=СЛЕДУЮЩИЙ_ШАГ,
            ),
        )
    )


def _сообщение(текст: str) -> Сообщение:
    return Сообщение(
        текст=текст,
        товарные_группы=("моторные масла",),
        события=(Событие(операция="приёмка", дата=date(2026, 3, 15)),),
    )


def test_вопрос_с_группой_операцией_и_датой_получает_один_ответ() -> None:
    результат = ход_диалога(
        дата_вопроса=date(2026, 10, 21),
        диалог=Диалог(),
        сообщение=_сообщение(
            "Какой следующий шаг при приёмке моторных масел 15 марта 2026?"
        ),
        хзчз=_хранилище(),
    )

    assert результат.ответ.товарная_группа == "моторные масла"
    assert [
        (пара.дата_нормы, пара.источник, пара.следующий_шаг)
        for пара in результат.ответ.пары
    ] == [(date(2026, 3, 15), ИСТОЧНИК, СЛЕДУЮЩИЙ_ШАГ)]


def test_короткий_вопрос_и_просьба_собрать_материал_дают_один_вид_ответа() -> None:
    короткий = ход_диалога(
        дата_вопроса=date(2026, 10, 21),
        диалог=Диалог(),
        сообщение=_сообщение("Приёмка моторных масел 15 марта 2026"),
        хзчз=_хранилище(),
    )
    сбор = ход_диалога(
        дата_вопроса=date(2026, 10, 21),
        диалог=Диалог(),
        сообщение=_сообщение(
            "Собери материал по приёмке моторных масел 15 марта 2026"
        ),
        хзчз=_хранилище(),
    )

    assert (
        сбор.ответ.товарная_группа,
        [
            (пара.дата_нормы, пара.источник, пара.следующий_шаг)
            for пара in сбор.ответ.пары
        ],
    ) == (
        "моторные масла",
        [(date(2026, 3, 15), ИСТОЧНИК, СЛЕДУЮЩИЙ_ШАГ)],
    )
    assert (
        короткий.ответ.товарная_группа,
        [
            (пара.дата_нормы, пара.источник, пара.следующий_шаг)
            for пара in короткий.ответ.пары
        ],
    ) == (
        сбор.ответ.товарная_группа,
        [
            (пара.дата_нормы, пара.источник, пара.следующий_шаг)
            for пара in сбор.ответ.пары
        ],
    )


def test_ход_не_меняет_хзчз() -> None:
    хзчз = _хранилище()
    нормы_до = хзчз.нормы

    ход_диалога(
        дата_вопроса=date(2026, 10, 21),
        диалог=Диалог(),
        сообщение=_сообщение(
            "Какой следующий шаг при приёмке моторных масел 15 марта 2026?"
        ),
        хзчз=хзчз,
    )

    assert хзчз.нормы == нормы_до
    assert хзчз.нормы[0].следующий_шаг == СЛЕДУЮЩИЙ_ШАГ


def test_ход_не_подаёт_сведения() -> None:
    результат = ход_диалога(
        дата_вопроса=date(2026, 10, 21),
        диалог=Диалог(),
        сообщение=_сообщение(
            "Какой следующий шаг при приёмке моторных масел 15 марта 2026?"
        ),
        хзчз=_хранилище(),
    )

    assert not hasattr(результат, "подача_сведений")
    assert [пара.следующий_шаг for пара in результат.ответ.пары] == [
        СЛЕДУЮЩИЙ_ШАГ
    ]
