def test_явный_выбор_держится_пока_его_не_сменят() -> None:
    выбран = ход_диалога(
        дата_вопроса=ДАТА_ВОПРОСА,
        диалог=Диалог(),
        сообщение=Сообщение(
            текст="Моторные масла",
            названные_группы=(),
            события=(Событие(операция="приёмка", дата=ДАТА_НОРМЫ),),
            явный_выбор="моторные масла",
        ),
        хзчз=_хранилище(),
    )
    удержан = ход_диалога(
        дата_вопроса=ДАТА_ВОПРОСА,
        диалог=выбран.диалог,
        сообщение=Сообщение(
            текст="Какой следующий шаг при приёмке молочной продукции 15 марта 2026?",
            названные_группы=("молочная продукция",),
            события=(Событие(операция="приёмка", дата=ДАТА_НОРМЫ),),
        ),
        хзчз=_хранилище(),
    )
    сменён = ход_диалога(
        дата_вопроса=ДАТА_ВОПРОСА,
        диалог=удержан.диалог,
        сообщение=Сообщение(
            текст="Молочная продукция",
            названные_группы=(),
            события=(Событие(операция="приёмка", дата=ДАТА_НОРМЫ),),
            явный_выбор="молочная продукция",
        ),
        хзчз=_хранилище(),
    )

    assert выбран.диалог == Диалог(
        товарная_группа="моторные масла",
        явный_выбор=True,
    )
    assert выбран.ответ.фраза_о_выборе is None
    assert [
        (пара.источник, пара.следующий_шаг) for пара in выбран.ответ.пары
    ] == [(ИСТОЧНИК_МАСЕЛ, ШАГ_МАСЕЛ)]
    assert удержан.диалог == выбран.диалог
    assert сменён.диалог == Диалог(
        товарная_группа="молочная продукция",
        явный_выбор=True,
    )
    assert сменён.ответ.фраза_о_выборе is None
    assert [
        (пара.источник, пара.следующий_шаг) for пара in сменён.ответ.пары
    ] == [(ИСТОЧНИК_МОЛОКА, ШАГ_МОЛОКА)]


