from datetime import date

from chezilla.ход import Диалог, Норма, Событие, Сообщение, ХЗЧЗ, ход_диалога


ДАТА_ВОПРОСА = date(2026, 10, 21)
ДАТА_НОРМЫ = date(2026, 3, 15)
ИСТОЧНИК_МАСЕЛ = "Постановление Правительства РФ от 26.04.2019 № 515"
ШАГ_МАСЕЛ = "Подать сведения о приёмке моторных масел"
ИСТОЧНИК_МОЛОКА = "Постановление Правительства РФ от 15.12.2020 № 2099"
ШАГ_МОЛОКА = "Подать сведения о приёмке молочной продукции"


def _норма(товарная_группа: str, источник: str, следующий_шаг: str) -> Норма:
    return Норма(
        товарная_группа=товарная_группа,
        операция="приёмка",
        действует_с=date(2026, 1, 1),
        действует_по=date(2026, 12, 31),
        источник=источник,
        следующий_шаг=следующий_шаг,
    )


def _хранилище() -> ХЗЧЗ:
    return ХЗЧЗ(
        нормы=(
            _норма("моторные масла", ИСТОЧНИК_МАСЕЛ, ШАГ_МАСЕЛ),
            _норма("молочная продукция", ИСТОЧНИК_МОЛОКА, ШАГ_МОЛОКА),
        )
    )


def test_без_группы_требование_не_назвать_назначает_одну_группу() -> None:
    результат = ход_диалога(
        дата_вопроса=ДАТА_ВОПРОСА,
        диалог=Диалог(),
        сообщение=Сообщение(
            текст="Какой следующий шаг при приёмке моторных масел 15 марта 2026?",
            названные_группы=("моторные масла",),
            события=(Событие(операция="приёмка", дата=ДАТА_НОРМЫ),),
        ),
        хзчз=_хранилище(),
    )

    assert результат.диалог == Диалог(товарная_группа="моторные масла")
    assert результат.ответ.товарная_группа == "моторные масла"
    assert результат.ответ.фраза_о_выборе == (
        "Советник выбрал товарную группу «моторные масла». "
        "Сменить её можно явным выбором."
    )
    assert результат.ответ.вопрос_о_группе is None
    assert [
        (пара.источник, пара.следующий_шаг) for пара in результат.ответ.пары
    ] == [(ИСТОЧНИК_МАСЕЛ, ШАГ_МАСЕЛ)]


