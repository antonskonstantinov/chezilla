def _строки_ответа(значение: object) -> list[str]:
    if isinstance(значение, str):
        return [значение]
    if isinstance(значение, tuple):
        строки: list[str] = []
        for элемент in значение:
            строки.extend(_строки_ответа(элемент))
        return строки
    if is_dataclass(значение) and not isinstance(значение, type):
        строки = []
        for поле in fields(значение):
            строки.extend(_строки_ответа(getattr(значение, поле.name)))
        return строки
    return []


