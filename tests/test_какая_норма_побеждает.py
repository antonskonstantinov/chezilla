def test_при_одном_охвате_побеждает_более_сильный_акт() -> None:
    охват = Охват(товарные_группы=("моторные масла", "молочная продукция"))
    состязания = (
        (
            СилаАкта.федеральный_закон,
            "Федеральный закон от 28.12.2009 № 381-ФЗ",
            "Подать сведения по федеральному закону",
            СилаАкта.акт_правительства,
            "Постановление Правительства РФ от 26.04.2019 № 515",
            "Подать сведения по акту Правительства",
        ),
        (
            СилаАкта.акт_правительства,
            "Постановление Правительства РФ от 26.04.2019 № 515",
            "Подать сведения по акту Правительства",
            СилаАкта.ведомственный_акт,
            "Приказ Минпромторга России от 28.04.2018 № 1562",
            "Подать сведения по ведомственному акту",
        ),
        (
            СилаАкта.ведомственный_акт,
            "Приказ Минпромторга России от 28.04.2018 № 1562",
            "Подать сведения по ведомственному акту",
            СилаАкта.официальная_публикация_оператора,
            "Официальная публикация оператора от 01.03.2024",
            "Подать сведения по публикации оператора",
        ),
    )
    for (
        сильнее,
        источник_сильнее,
        шаг_сильнее,
        слабее,
        источник_слабее,
        шаг_слабее,
    ) in состязания:
        результат = ход_диалога(
            дата_вопроса=ДАТА_ВОПРОСА,
            диалог=ДИАЛОГ,
            сообщение=_вопрос(),
            хзчз=ХЗЧЗ(
                блок_общих_норм=БлокОбщихНорм(
                    нормы=(
                        _общая(
                            источник=источник_слабее,
                            следующий_шаг=шаг_слабее,
                            охват=охват,
                            сила_акта=слабее,
                            вступила_в_силу=date(2020, 1, 1),
                        ),
                        _общая(
                            источник=источник_сильнее,
                            следующий_шаг=шаг_сильнее,
                            охват=охват,
                            сила_акта=сильнее,
                            вступила_в_силу=date(2020, 1, 1),
                        ),
                    )
                ),
            ),
        )

        assert результат.диалог == ДИАЛОГ
        пара = результат.ответ.пары[0]
        assert пара.источник == источник_сильнее
        assert пара.следующий_шаг == шаг_сильнее
        assert пара.охват == охват


