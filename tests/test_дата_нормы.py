from datetime import date

from chezilla.ход import Диалог, Норма, Событие, Сообщение, ХЗЧЗ, ход_диалога


ИСТОЧНИК = "Постановление Правительства РФ от 26.04.2019 № 515"
СЛЕДУЮЩИЙ_ШАГ = "Подать сведения о приёмке"


def _норма(
    *,
    действует_с: date,
    действует_по: date,
    источник: str = ИСТОЧНИК,
    следующий_шаг: str = СЛЕДУЮЩИЙ_ШАГ,
) -> Норма:
    return Норма(
        товарная_группа="моторные масла",
        операция="приёмка",
        действует_с=действует_с,
        действует_по=действует_по,
        источник=источник,
        следующий_шаг=следующий_шаг,
    )


def test_вопрос_без_дат_получает_днём_нормы_день_вопроса() -> None:
    день_вопроса = date(2026, 10, 21)
    результат = ход_диалога(
        дата_вопроса=день_вопроса,
        диалог=Диалог(),
        сообщение=Сообщение(
            текст="Какой следующий шаг при приёмке моторных масел?",
            товарные_группы=("моторные масла",),
            события=(Событие(операция="приёмка"),),
        ),
        хзчз=ХЗЧЗ(
            нормы=(
                _норма(
                    действует_с=date(2026, 1, 1),
                    действует_по=date(2026, 12, 31),
                ),
            )
        ),
    )

    assert результат.ответ.товарная_группа == "моторные масла"
    assert [пара.дата_нормы for пара in результат.ответ.пары] == [день_вопроса]
    assert [пара.фраза_дня_вопроса for пара in результат.ответ.пары] == [
        "Дата нормы — день вопроса."
    ]
    assert [пара.источник for пара in результат.ответ.пары] == [ИСТОЧНИК]
    assert [пара.следующий_шаг for пара in результат.ответ.пары] == [
        СЛЕДУЮЩИЙ_ШАГ
    ]


def test_два_события_получают_две_даты_нормы() -> None:
    результат = ход_диалога(
        дата_вопроса=date(2026, 10, 21),
        диалог=Диалог(),
        сообщение=Сообщение(
            текст="Приёмка 1 марта 2026 и приёмка 15 марта 2026",
            товарные_группы=("моторные масла",),
            события=(
                Событие(операция="приёмка", дата=date(2026, 3, 1)),
                Событие(операция="приёмка", дата=date(2026, 3, 15)),
            ),
        ),
        хзчз=ХЗЧЗ(
            нормы=(
                _норма(
                    действует_с=date(2026, 1, 1),
                    действует_по=date(2026, 12, 31),
                ),
            )
        ),
    )

    assert [пара.дата_нормы for пара in результат.ответ.пары] == [
        date(2026, 3, 1),
        date(2026, 3, 15),
    ]
    assert [пара.источник for пара in результат.ответ.пары] == [
        ИСТОЧНИК,
        ИСТОЧНИК,
    ]
    assert [пара.следующий_шаг for пара in результат.ответ.пары] == [
        СЛЕДУЮЩИЙ_ШАГ,
        СЛЕДУЮЩИЙ_ШАГ,
    ]


