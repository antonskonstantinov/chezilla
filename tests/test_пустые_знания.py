ИСТОЧНИК_ПРАКТИКИ_СОСЕДА = "Запись поддержки по приёмке молока"
СПОСОБ_СОСЕДА = "Повторить приёмку молока после смены статуса"
ИСТОЧНИК_ДРУГОЙ_ДАТЫ = "Постановление Правительства РФ от 01.12.2025 № 1732"
ШАГ_ДРУГОЙ_ДАТЫ = "Подать сведения о приёмке в редакции 2025 года"
ИСТОЧНИК_ПРАКТИКИ_ДРУГОЙ_ДАТЫ = "Запись поддержки по приёмке в 2027 году"
СПОСОБ_ДРУГОЙ_ДАТЫ = "Подать приёмку по форме 2027 года"
ИСТОЧНИК_РЕГЛАМЕНТА = "Регламент СБИС, раздел приёмка"
ШАГ_РЕГЛАМЕНТА = "Нажать «Принять» в кабинете СБИС"
ИСТОЧНИК_ПРАКТИКИ_ПРОВАЙДЕРА = "Переписка поддержки СБИС по приёмке масел"
СПОСОБ_ПРОВАЙДЕРА = "Повторить приёмку из кабинета СБИС"
ШАГ_БЕЗ_ИСТОЧНИКА = "Подать сведения из слоя без источника"
СПОСОБ_БЕЗ_ИСТОЧНИКА = "Повторить приёмку по слою без источника"
ИСТОЧНИК = "Постановление Правительства РФ от 26.04.2019 № 515"
СЛЕДУЮЩИЙ_ШАГ = "Подать сведения о приёмке"
ПУСТО = _Состав("В знаниях этого нет.", None, None, None, None)


def _ход(хзчз: ХЗЧЗ) -> РезультатХода:
    return ход_диалога(
        дата_вопроса=ДАТА_ВОПРОСА,
        диалог=Диалог(),
        сообщение=Сообщение(
            текст="Какой следующий шаг при приёмке моторных масел 15 марта 2026?",
            товарные_группы=("моторные масла",),
            события=(Событие(операция="приёмка", дата=ДАТА_НОРМЫ),),
        ),
        хзчз=хзчз,
    )


def _состав(результат: РезультатХода) -> list[_Состав]:
    return [
        _Состав(
            пара.фраза_пустых_знаний,
            пара.источник,
            пара.источник_практики,
            пара.способ,
            пара.следующий_шаг,
        )
        for пара in результат.ответ.пары
    ]


def _норма(
    *,
    источник: str | None,
    следующий_шаг: str,
    товарная_группа: str = "моторные масла",
    действует_с: date = date(2026, 1, 1),
    действует_по: date = date(2026, 12, 31),
) -> Норма:
    return Норма(
        товарная_группа=товарная_группа,
        операция="приёмка",
        действует_с=действует_с,
        действует_по=действует_по,
        источник=источник,
        следующий_шаг=следующий_шаг,
    )


def _практика(
    *,
    источник: str | None,
    способ: str,
    действует_с: date = date(2026, 1, 1),
    действует_по: date = date(2026, 12, 31),
) -> Практика:
    return Практика(
        операция="приёмка",
        действует_с=действует_с,
        действует_по=действует_по,
        источник=источник,
        способ=способ,
    )


def test_нет_нормы_и_практики_на_группу_и_дату_говорит_что_в_знаниях_этого_нет() -> None:
    результат = _ход(ХЗЧЗ())

    assert результат.диалог == Диалог(товарная_группа="моторные масла")
    assert [пара.дата_нормы for пара in результат.ответ.пары] == [ДАТА_НОРМЫ]
    assert _состав(результат) == [ПУСТО]


def test_практика_этой_группы_и_даты_не_оставляет_ответ_пустым() -> None:
    результат = _ход(
        ХЗЧЗ(
            блоки_групп=(
                БлокГруппы(
                    товарная_группа="моторные масла",
                    практики=(_практика(источник=ИСТОЧНИК_ПРАКТИКИ, способ=СПОСОБ),),
                ),
            )
        )
    )

    assert _состав(результат) == [
        _Состав(None, None, ИСТОЧНИК_ПРАКТИКИ, СПОСОБ, СПОСОБ)
    ]
    assert результат.ответ.пары[0].фраза_нет_нормы == "Нормы на эту дату нет."
    assert результат.ответ.пары[0].фраза_оговорки is None


