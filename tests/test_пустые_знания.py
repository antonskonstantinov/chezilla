def test_слой_без_источника_не_вытесняет_норму_с_источником() -> None:
    результат = _ход(
        ХЗЧЗ(
            блоки_групп=(
                БлокГруппы(
                    товарная_группа="моторные масла",
                    нормы=(
                        _норма(источник=None, следующий_шаг=ШАГ_БЕЗ_ИСТОЧНИКА),
                        _норма(источник=ИСТОЧНИК, следующий_шаг=СЛЕДУЮЩИЙ_ШАГ),
                    ),
                    практики=(
                        _практика(источник=None, способ=СПОСОБ_БЕЗ_ИСТОЧНИКА),
                    ),
                ),
            )
        )
    )

    assert _состав(результат) == [
        _Состав(None, ИСТОЧНИК, None, None, СЛЕДУЮЩИЙ_ШАГ)
    ]
